import os

import bpy

repo = r"E:\SpaghettiKart"
out = os.path.join(repo, "src", "first_person_kart_mesh.inc.c")
body_object_name = "export_first_person_kart_body"

precision = 8.0
scale_macro = 0.125

material_groups = [
    ("recolor", "sMeshyKartBodyRecolor", "character recolor region"),
    ("silver", "sMeshyKartBodySilver", "silver frame/metal"),
    ("blue", "sMeshyKartBodyBlue", "small blue accent"),
    ("dark", "sMeshyKartBodyDark", "dark seat/engine/detail"),
]


def material_group(obj, material_index):
    if material_index < len(obj.data.materials):
        mat = obj.data.materials[material_index]
        if mat is not None:
            name = mat.name.lower()
            if "recolor" in name or "red" in name:
                return "recolor"
            if "silver" in name or "metal" in name:
                return "silver"
            if "blue" in name:
                return "blue"
            if "dark" in name or "black" in name:
                return "dark"
    return "dark"


def write_display_list(f, symbol, tri_count):
    tri_base = 0
    while tri_base < tri_count:
        chunk = min(10, tri_count - tri_base)
        vb = tri_base * 3
        f.write(f"    gsSPVertex({symbol}Vtx + {vb}, {chunk * 3}, 0),\n")
        local = 0
        while local + 1 < chunk:
            a0 = local * 3
            a1 = (local + 1) * 3
            f.write(f"    gsSP2Triangles({a0}, {a0 + 1}, {a0 + 2}, 0, {a1}, {a1 + 1}, {a1 + 2}, 0),\n")
            local += 2
        if local < chunk:
            a0 = local * 3
            f.write(f"    gsSP1Triangle({a0}, {a0 + 1}, {a0 + 2}, 0),\n")
        tri_base += chunk


obj = bpy.data.objects.get(body_object_name)
if obj is None:
    selected = [candidate for candidate in bpy.context.selected_objects if candidate.type == "MESH"]
    if len(selected) == 1:
        obj = selected[0]
    else:
        raise RuntimeError(f"Missing body object: {body_object_name}")
if obj.type != "MESH":
    raise RuntimeError(f"{obj.name} is not a mesh")

if bpy.context.mode != "OBJECT":
    bpy.ops.object.mode_set(mode="OBJECT")

bpy.ops.object.select_all(action="DESELECT")
obj.select_set(True)
bpy.context.view_layer.objects.active = obj

for poly in obj.data.polygons:
    poly.use_smooth = True
obj.data.update()

depsgraph = bpy.context.evaluated_depsgraph_get()
eval_obj = obj.evaluated_get(depsgraph)
mesh = bpy.data.meshes.new_from_object(eval_obj, depsgraph=depsgraph)

triangulated = bpy.data.objects.new(f"{obj.name}_tri_export", mesh)
bpy.context.collection.objects.link(triangulated)
bpy.ops.object.select_all(action="DESELECT")
triangulated.select_set(True)
bpy.context.view_layer.objects.active = triangulated
tri = triangulated.modifiers.new("triangulate_for_mk64", "TRIANGULATE")
tri.quad_method = "BEAUTY"
tri.ngon_method = "BEAUTY"
bpy.ops.object.modifier_apply(modifier=tri.name)
mesh = triangulated.data

vertices_by_group = {group[0]: [] for group in material_groups}
tri_counts = {group[0]: 0 for group in material_groups}
tri_count = 0

for poly in mesh.polygons:
    if len(poly.vertices) != 3:
        continue
    group = material_group(obj, poly.material_index)
    tri_counts[group] += 1
    tri_count += 1
    for vertex_index in poly.vertices:
        co = mesh.vertices[vertex_index].co
        # Blender scene uses X = right, Y = kart forward, Z = up.
        # The first-person render matrix uses local X = right, Y = up, Z = forward.
        x = int(round(co.x * precision))
        y = int(round(co.z * precision))
        z = int(round(co.y * precision))
        vertices_by_group[group].append((x, y, z, 255, 255, 255, 255))

bpy.data.objects.remove(triangulated, do_unlink=True)

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by artifacts/scripts/export_first_person_body_from_blender.py. */\n")
    f.write(f"/* Source object: {obj.name}. */\n")
    f.write(f"/* Triangulated to {tri_count} triangles and stored at 8x coordinate precision. */\n\n")
    f.write(f"#define FP_MESHY_KART_BODY_SCALE {scale_macro}f\n")
    f.write(f"#define FP_MESHY_KART_BODY_TRIANGLE_COUNT {tri_count}\n\n")
    for group, _, _ in material_groups:
        f.write(f"#define FP_MESHY_KART_BODY_{group.upper()}_TRIANGLE_COUNT {tri_counts[group]}\n")
    f.write("\n")

    for group, symbol, description in material_groups:
        f.write(f"/* {description}. */\n")
        if tri_counts[group] > 0:
            f.write(f"static Vtx {symbol}Vtx[] = {{\n")
            for x, y, z, r, g, b, a in vertices_by_group[group]:
                f.write(
                    f"    {{{{ {{ {x}, {y}, {z} }}, 0, {{ 0, 0 }}, "
                    f"{{ 0x{r:02X}, 0x{g:02X}, 0x{b:02X}, 0x{a:02X} }} }}}},\n"
                )
            f.write("};\n\n")
        f.write(f"static Gfx {symbol}Dl[] = {{\n")
        if tri_counts[group] > 0:
            write_display_list(f, symbol, tri_counts[group])
        f.write("    gsSPEndDisplayList(),\n")
        f.write("};\n\n")

bpy.ops.object.select_all(action="DESELECT")
obj.select_set(True)
bpy.context.view_layer.objects.active = obj

print(f"Wrote {out}")
print(f"{obj.name}: tris={tri_count} verts={len(obj.data.vertices)}")
for group, _, _ in material_groups:
    print(f"{group}: tris={tri_counts[group]}")
